<?php

namespace Tests\Feature\Floor;

use Tests\TestCase;

/**
 * card#12442 — A WALKER MOVES LIKE A PERSON IN A BUILDING (`docs/design/FLOOR.md § 6.2`'s walk note item 3, § 12's
 * *Walker clearance* and *Walkway centring* rows): along every route, the walker's drawn body — the character's rect,
 * its feet at the rect's bottom centre — never stands over a wall or a standing tile beside or in front of its feet,
 * nor over another desk; on a route found at the `clear` tier it keeps § 12's margins too; and in a walkway it keeps
 * to the middle.
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────────
 * ⛔ THE PROPERTY IS RE-DERIVED HERE, ALONG THE DRAWN POLYLINE, NEVER READ FROM THE LATTICE. `route.js` blocks cells by
 * their centres; this test samples the feet every pixel of every segment the painter glides along — the desk's anchor
 * and the elevator's threshold included — and holds each sample's body to the rects `walk-probe.mjs` resolves through
 * the scene's own tile reader. The body is the probe's `body`, which is `scene.js`'s `walkerSize()`: the size every
 * walk effect is drawn at. A wall wholly above the feet on screen is behind the walker in the three-quarter view and is
 * not an overlap (the seat's ruling on card#12442).
 *
 * ⛔ TWO FLOORS. The shipped default (`resources/floor/default.tmj`), and `fixtures/maps/solo-cubicles.json`: the
 * back-to-back cubicle floor the operator reported the defect on, generated by the seat's recipe for it (card#12442)
 * rather than copied from the stored map. Every number about either floor is read from the map here.
 *
 * ⛔ EACH RED IS A PLANT, seen to break the GREEN it guards: the lattice before card#12442 (the feet rule alone), a
 * column narrowed past the margins (a tier drops), a gap narrower than the body (the feet rule's squeeze is seen), and
 * the centring switched off.
 */
class AWalkerKeepsClearOfWallsAndFurnitureTest extends TestCase
{
    use DrivesTheFloorScreen;

    private const ROUTE = '../floor/route.js';

    private const CUBICLES = __DIR__.'/fixtures/maps/solo-cubicles.json';

    // ── § 12's rows, read out of the document ────────────────────────────────────────────────

    /** @return array{margin: int, depth: int} § 12's *Walker clearance* row */
    private function clearance(): array
    {
        $this->assertSame(1, preg_match('/^\| \*\*Walker clearance\*\* \| \*\*(\d+) px beside; (\d+) px in depth\*\* \|/m', $this->floorMd(), $m),
            '§ 12 carries no *Walker clearance* row in the form this test reads');

        return ['margin' => (int) $m[1], 'depth' => (int) $m[2]];
    }

    /** @return array{reach: int, weight: int} § 12's *Walkway centring* row */
    private function centring(): array
    {
        $this->assertSame(1, preg_match('/^\| \*\*Walkway centring\*\* \| \*\*(\d+) px; weight (\d+)\*\* \|/m', $this->floorMd(), $m),
            '§ 12 carries no *Walkway centring* row in the form this test reads');

        return ['reach' => (int) $m[1], 'weight' => (int) $m[2]];
    }

    // ── The probe ───────────────────────────────────────────────────────────────────────────────

    /** A floor as the scene reads it, every desk routed to the elevator (`walk-probe.mjs`'s `shipped`). */
    private function floor(?string $map = null, ?string $dir = null, array $walls = []): array
    {
        return $this->probe(['mode' => 'shipped', 'map' => $map, 'walls' => $walls], $dir, __DIR__.'/walk-probe.mjs');
    }

    private function map(string $path): array
    {
        return json_decode((string) file_get_contents($path), true);
    }

    private function defaultMapPath(): string
    {
        return (string) realpath(base_path('../resources/floor/default.tmj'));
    }

    // ── The property ────────────────────────────────────────────────────────────────────────────

    /**
     * Where one desk's walker stands over something it must not, sampled every pixel along its drawn polyline: a wall
     * or standing rect within `$side` px of the feet sideways while the feet are within `$depth` px of its depth span,
     * or another desk's slot or box under the bare body while the feet are inside its depth span.
     *
     * @return list<string> the first defect of the desk, or none
     */
    private function bodyDefects(array $floor, array $desk, float $side, float $depth): array
    {
        $half = $floor['body']['w'] / 2;
        $rects = [];

        foreach ($floor['obstacles'] as $o) {
            $rects[] = [$o, $side, $depth, $o['kind']];
        }

        foreach ($floor['desks'] as $other) {
            if ($other['key'] !== $desk['key']) {
                foreach ([$other['slot'], $other['box']] as $r) {
                    $rects[] = [$r, $half, 0.0, $other['key']];
                }
            }
        }

        $points = $desk['points'] ?? [];

        for ($i = 1; $i < count($points); $i++) {
            [$a, $b] = [$points[$i - 1], $points[$i]];
            $n = max(1, (int) ceil(hypot($b['x'] - $a['x'], $b['y'] - $a['y'])));

            for ($k = 0; $k <= $n; $k++) {
                $p = ['x' => $a['x'] + ($b['x'] - $a['x']) * $k / $n, 'y' => $a['y'] + ($b['y'] - $a['y']) * $k / $n];

                foreach ($rects as [$r, $s, $d, $what]) {
                    if ($p['x'] - $s < $r['x'] + $r['w'] && $r['x'] < $p['x'] + $s && $r['y'] - $d < $p['y'] && $p['y'] < $r['y'] + $r['h'] + $d) {
                        return ["{$desk['key']} ({$desk['clearance']}): feet at ".json_encode($p)." stand within {$s} px beside / {$d} px in depth of {$what} ".json_encode([$r['x'], $r['y'], $r['w'], $r['h']])];
                    }
                }
            }
        }

        return [];
    }

    /** Every desk's defects at the bare body: nothing beside or in front of the feet, under the drawn rect. */
    private function bareDefects(array $floor): array
    {
        return array_merge(...array_map(fn ($d) => $this->bodyDefects($floor, $d, $floor['body']['w'] / 2, 0.0), $floor['desks']));
    }

    /** Every `clear` desk's defects at § 12's margins. */
    private function marginDefects(array $floor): array
    {
        $c = $this->clearance();
        $clear = array_filter($floor['desks'], static fn ($d) => $d['clearance'] === 'clear');

        return array_merge([], ...array_map(fn ($d) => $this->bodyDefects($floor, $d, $floor['body']['w'] / 2 + $c['margin'], $c['depth']), $clear));
    }

    /** @return array<string, string|null> each desk's tier */
    private function tiers(array $floor): array
    {
        return array_column($floor['desks'], 'clearance', 'key');
    }

    /**
     * The cubicles' two body-wide walkways along the floor's edges, read from the map: the side walkway between the
     * floor's left edge and the leftmost wall column, and the front walkway between the lowest wall row and the
     * floor's bottom edge. For each desk whose route uses it, the feet's commonest position across it, against the
     * walkway's middle.
     *
     * @return list<string> the walkways a route does not keep to the middle of, by more than one cell
     */
    private function centringDefects(array $floor): array
    {
        $map = $this->map(self::CUBICLES);
        $walls = array_values(array_filter($map['layers'], static fn ($l) => $l['name'] === 'walls'))[0]['data'];
        $w = $map['width'];
        $c = $floor['cell'];
        $cols = array_map(static fn ($i) => $i % $w, array_keys(array_filter($walls)));
        $rows = array_map(static fn ($i) => intdiv($i, $w), array_keys(array_filter($walls)));
        $side = ['axis' => 'x', 'from' => 0, 'to' => min($cols) * $c, 'in' => fn ($p) => $p['x'] < min($cols) * $c && $p['y'] > min($rows) * $c];
        $front = ['axis' => 'y', 'from' => (max($rows) + 1) * $c, 'to' => $floor['extent']['height'], 'in' => fn ($p) => $p['y'] > (max($rows) + 1) * $c];
        $defects = [];
        $measured = 0;

        foreach ($floor['desks'] as $desk) {
            foreach (['side' => $side, 'front' => $front] as $name => $way) {
                $at = [];

                foreach (array_slice($desk['points'] ?? [], 1, -1) as $p) {
                    if (($way['in'])($p)) {
                        $at[(string) $p[$way['axis']]] = ($at[(string) $p[$way['axis']]] ?? 0) + 1;
                    }
                }

                if ($at === []) {
                    continue;
                }

                arsort($at);
                $mode = (float) array_key_first($at);
                $middle = ($way['from'] + $way['to']) / 2;
                $measured++;

                if (abs($mode - $middle) > $c) {
                    $defects[] = "{$desk['key']} keeps to {$way['axis']} {$mode} in the {$name} walkway, whose middle is {$middle}";
                }
            }
        }

        $this->assertGreaterThan(0, $measured, 'no route used either walkway — the centring guard measured nothing');

        return $defects;
    }

    // ── The GREENs ──────────────────────────────────────────────────────────────────────────────

    /** The shipped default: every desk walks at `clear`, nothing under the body, the margins kept. */
    public function test_green_every_desk_of_the_shipped_default_walks_clear(): void
    {
        $floor = $this->floor($this->defaultMapPath());

        $this->assertNotSame([], $floor['desks']);
        $this->assertSame(array_fill_keys(array_column($floor['desks'], 'key'), 'clear'), $this->tiers($floor),
            'a desk of the shipped default does not reach the elevator at the clear tier');
        $this->assertSame([], $this->bareDefects($floor));
        $this->assertSame([], $this->marginDefects($floor));
    }

    /**
     * The cubicle floor: every desk walks, none on the feet rule alone, nothing under the body, the margins kept by every
     * `clear` route — and the walkways along the floor's edges walked down their middle. A desk whose own lane beside it is
     * narrower than the body and both margins walks at `snug`, which is the tiers doing their job and is printed.
     */
    public function test_green_every_desk_of_the_cubicles_walks_without_touching_a_wall(): void
    {
        $floor = $this->floor(self::CUBICLES);
        $tiers = $this->tiers($floor);

        fwrite(STDERR, "\n[card#12442] the cubicles' tiers: ".json_encode($tiers)."\n");
        $this->assertNotSame([], $tiers);
        $this->assertSame([], array_keys(array_filter($tiers, static fn ($t) => ! in_array($t, ['clear', 'snug'], true))),
            'a desk of the cubicles walks on the feet rule alone, or not at all');
        $this->assertContains('clear', $tiers);
        $this->assertSame([], $this->bareDefects($floor));
        $this->assertSame([], $this->marginDefects($floor));
        $this->assertSame([], $this->centringDefects($floor));
    }

    /** The tier a walk was routed at is on the walk effect the scene draws. */
    public function test_green_the_walk_carries_its_tier(): void
    {
        $result = $this->floorRun('leave-stale');
        $walks = [];

        foreach ($result['floor_renders'] as $r) {
            foreach ($r['frame']['scene']['effects'] ?? [] as $e) {
                if (in_array($e['animation_id'], ['A1', 'A2'], true)) {
                    $walks[] = [$e['route'], $e['clearance']];
                }
            }
        }

        $this->assertContains(['routed', 'clear'], $walks, 'no routed walk of the shipped default carries its clear tier');
        $this->assertSame([], array_filter($walks, static fn ($w) => $w[0] === 'routed' && ! in_array($w[1], ['clear', 'snug', 'feet'], true)));
    }

    /** § 12's two rows are `route.js`'s constants. */
    public function test_green_section_12_is_the_routes_clearance(): void
    {
        $route = (string) file_get_contents($this->moduleDir().'/'.self::ROUTE);

        $this->assertSame(1, preg_match('/export const CLEARANCE = Object\.freeze\(\{ margin: (\d+), depth: (\d+) \}\);/', $route, $m));
        $this->assertSame($this->clearance(), ['margin' => (int) $m[1], 'depth' => (int) $m[2]], '§ 12\'s *Walker clearance* is not route.js\'s CLEARANCE');
        $this->assertSame(1, preg_match('/export const CENTRING = Object\.freeze\(\{ reach: (\d+), weight: (\d+) \}\);/', $route, $m));
        $this->assertSame($this->centring(), ['reach' => (int) $m[1], 'weight' => (int) $m[2]], '§ 12\'s *Walkway centring* is not route.js\'s CENTRING');
    }

    // ── The REDs ────────────────────────────────────────────────────────────────────────────────

    /** The lattice before card#12442 — the feet rule alone: bodies stand over walls and furniture on both floors. */
    public function test_red_the_feet_rule_alone(): void
    {
        $dir = $this->mutatedModules([self::ROUTE, "export const CLEARANCE_TIERS = Object.freeze(['clear', 'snug', 'feet']);", "export const CLEARANCE_TIERS = Object.freeze(['feet']);"]);

        $this->assertNotSame([], $this->bareDefects($this->floor($this->defaultMapPath(), $dir)), 'the shipped default\'s feet-rule routes put no body over a wall or furniture');
        $this->assertNotSame([], $this->bareDefects($this->floor(self::CUBICLES, $dir)), 'the cubicles\' feet-rule routes put no body over a wall or furniture');
    }

    /**
     * A wall column planted down the shipped default's elevator room, leaving its one body-wide exit wide enough for the
     * body but not for the margins: every desk still walks, at `snug`, nothing under the body — and the margin guard sees
     * the margin given up.
     */
    public function test_red_a_column_narrowed_past_the_margins_drops_to_snug(): void
    {
        $floor = $this->floor($this->defaultMapPath(), null, $this->plantedColumn(4));
        $tiers = $this->tiers($floor);

        $this->assertContains('snug', $tiers, 'CONTROL (the column narrowed past the margins) left every desk at clear');
        $this->assertNotContains('feet', $tiers);
        $this->assertSame([], $this->bareDefects($floor));
        $snug = array_values(array_filter($floor['desks'], static fn ($d) => $d['clearance'] === 'snug'));
        $c = $this->clearance();
        $this->assertNotSame([], $this->bodyDefects($floor, $snug[0], $floor['body']['w'] / 2 + $c['margin'], $c['depth']),
            'a snug route kept the margins — the plant did not narrow the column past them');
    }

    /** The same column narrower than the body: the desks still walk, on the feet rule, and the body guard sees it. */
    public function test_red_a_gap_narrower_than_the_body_walks_on_the_feet_rule(): void
    {
        $floor = $this->floor($this->defaultMapPath(), null, $this->plantedColumn(5));

        $this->assertContains('feet', $this->tiers($floor), 'CONTROL (a gap narrower than the body) left no desk on the feet rule');
        $this->assertSame([], array_keys(array_filter($this->tiers($floor), static fn ($t) => $t === null)), 'a desk stopped walking');
        $this->assertNotSame([], $this->bareDefects($floor), 'the body guard did not see a body squeezed through a gap narrower than itself');
    }

    /** The centring switched off: the cubicles' walkways are walked along an edge. */
    public function test_red_the_centring_off(): void
    {
        $dir = $this->mutatedModules([self::ROUTE, 'return d.map((v) => CENTRING.weight * Math.max(0, R - v));', 'return d.map(() => 0);']);

        $this->assertNotSame([], $this->centringDefects($this->floor(self::CUBICLES, $dir)), 'the cubicles\' walkways are walked down their middle with no centring cost');
    }

    /**
     * Wall tiles down the shipped default's elevator-room column, at tile column `$col` from the floor's top to the
     * room's front: the column between them and the room's first desk is that room's one body-wide exit.
     *
     * @return list<array{0: int, 1: int}>
     */
    private function plantedColumn(int $col): array
    {
        $map = $this->map($this->defaultMapPath());
        $desks = array_values(array_filter($map['layers'], static fn ($l) => $l['name'] === 'desks'))[0]['objects'];
        $first = array_reduce($desks, static fn ($a, $o) => $a === null || $o['x'] < $a['x'] || ($o['x'] === $a['x'] && $o['y'] < $a['y']) ? $o : $a);
        $front = intdiv($first['y'] + $first['height'], $map['tileheight']);

        return array_map(static fn ($row) => [$col, $row], range(1, $front));
    }
}
