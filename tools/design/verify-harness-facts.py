# ---------- which build is ground truth: READ from D1, never restated here ---------
# D1 states its capture build in five places (verified 2026-08-27: § preamble, § 6.0 twice,
# § 14's provenance row, § 17's capture-seat row).  All five are load-bearing (a reader who
# lands on any one of them takes it as the version its MEASURED facts hold at), so the
# derivation requires them to agree: a run over a document whose sites disagree cannot
# say which build it is binding to and reports that rather than picking one.
DECLARED_BUILD_SITES = {
    "the § preamble status block":
        r"captured from Claude Code \*\*(\d+\.\d+\.\d+)\*\*",
    "§ 6.0's measurement-of-record paragraph":
        r"were captured on \*\*[\d-]+\*\* from \*\*Claude Code (\d+\.\d+\.\d+)\*\* on Linux",
    "§ 6.0's re-capture obligation":
        r"Every MEASURED fact in this document is versioned to (\d+\.\d+\.\d+)",
    "§ 14's provenance row":
        r"\| Harness build the MEASURED facts are pinned to \| Claude Code \*\*(\d+\.\d+\.\d+)\*\*",
    "§ 17's capture-seat row":
        r"\| Harness \| \*\*Claude Code (\d+\.\d+\.\d+)\*\*",
}

def declared_build(doc_text):
    """The build D1 says its MEASURED facts were captured at, or None with a reason."""
    found, missing = {}, []
    for site, pat in DECLARED_BUILD_SITES.items():
        m = re.search(pat, doc_text)
        if m:
            found[site] = m.group(1)
        else:
            missing.append(site)
    if missing:
        return None, ("D1's declared harness build cannot be read at: "
                      + ", ".join(missing)
                      + " — the ground-truth build cannot be derived, so this check reports "
                        "nothing rather than binding to a build nobody declared")
    if len(set(found.values())) != 1:
        return None, ("D1 declares more than one capture build — "
                      + "; ".join(f"{s} says {v}" for s, v in sorted(found.items()))
                      + " — re-mark every site to the build the capture was actually run at")
    return next(iter(found.values())), None

