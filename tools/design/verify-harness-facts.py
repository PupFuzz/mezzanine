#!/usr/bin/env python3
"""D1 verification gate: bind this document's harness facts to the installed harness binary.

Two bindings, one rung apart:

  * KEY NAMES (rounds 3+).  Every fixture key in the appendix must be a key the installed
    build's own payload schema declares for that hook.
  * ENUM VALUE SETS (round 4).  Every harness-sourced enum's value set is re-derived from
    the binary and asserted against EVERY place the document states it.  Round 3 bound key
    names and built a guard for them; it did not bind value sets, which is how a
    `notification_type` row carrying 14 of the build's 16 declared members survived three
    review rounds -- omitting exactly the two the `elicitation` branch depends on.

Ground truth is the INSTALLED HARNESS BINARY's own declarations, re-derived on every run.
Nothing here is a stored FACT -- not a number, not a key name, not a minified identifier --
and every extractor carries a control that ABORTS rather than reporting clean when it cannot
discriminate (canon #9: a check that cannot fail is a decoration).  "Number" is what that
sentence said until card#7947, and a transcribed list of the harness's nine COMMON payload
key names sat below it the whole time, backing most of the fixture-key assertions in § 1.

WHICH build is ground truth is D1's fact, not this tool's: the version is READ from the
document's own declaration sites and this file states it nowhere.  A version typed here
would be a restatement with neither a pointer nor a guard -- the exact defect class D1
§ 6.0 is written about, one level up.  Likewise nothing here is pinned to a minified
identifier: those are regenerated by the bundler on every build (`literal()` was `Ht` at
2.1.240, `o` at 2.1.243-2.1.246, `n` at 2.1.247), so a pinned one is a second dead pin
wearing a different costume.  Shapes are matched; names are derived.

Environment:
  MEZZ_HARNESS_BIN       path to the harness bundle to read as ground truth.  Overrides
                         the default and is NAMED on every run, together with the fact
                         that it is not the build D1 declares.
  MEZZ_CLAUDE_VERSIONS   directory holding the installed bundles.  Default: the directory
                         the `claude` on PATH resolves into, else ~/.local/share/claude/versions.
"""
